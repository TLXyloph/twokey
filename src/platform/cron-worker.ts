/**
 * The Worker's entry (wrangler.jsonc `main`): OpenNext's generated handler, plus the Watchtower's
 * Cron Trigger. An OpenNext "custom worker" (https://opennext.js.org/cloudflare/howtos/custom-worker,
 * checked 2026-11-05): it re-uses the generated fetch handler, re-exports the Durable Object
 * classes the generated worker exports, and adds `scheduled()`, which POSTs
 * /api/watchtower/run on that same fetch handler with the Bearer secret (src/watchtower/cron.ts).
 *
 * `.open-next/worker.js` exists only after `opennextjs-cloudflare build` (npm run build:worker),
 * so its imports are `@ts-ignore`d: `tsc --noEmit` passes with or without a build. wrangler
 * bundles this file at deploy time, after the build. Relative imports only: wrangler, not Next,
 * bundles it.
 */
// @ts-ignore -- generated by `opennextjs-cloudflare build`; absent before the first build
import openNextWorker from "../../.open-next/worker.js";
import { runScheduledWatch } from "../watchtower/cron";
import type {} from "./cloudflare-env"; // the CloudflareEnv bindings (DB, secrets, vars)

// @ts-ignore -- generated at build time (see above); the classes OpenNext's own worker exports
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "../../.open-next/worker.js";

interface ExecutionContextLike {
  waitUntil(promise: Promise<unknown>): void;
}

interface WorkerFetch {
  fetch(request: Request, env: CloudflareEnv, ctx: ExecutionContextLike): Promise<Response>;
}

const handler = openNextWorker as WorkerFetch;

export default {
  fetch: handler.fetch,
  scheduled(_controller: unknown, env: CloudflareEnv, ctx: ExecutionContextLike): void {
    ctx.waitUntil(runScheduledWatch(handler.fetch, env, ctx));
  },
};
